/**
 * starfield.mjs — generates assets/css/starfield.css.
 *
 * WHY THIS EXISTS
 * The star fill inside display type started as hand-written radial-gradients.
 * That caps out fast: one CSS layer per star, so ~18 stars meant roughly a dozen
 * survived inside the glyph strokes and the effect read as nothing at all.
 * Scaling that approach to the density the type actually needs would mean
 * thousands of gradient layers, which no engine will composite at speed.
 *
 * So each layer is instead ONE tiled SVG carrying hundreds of circles. Cost is a
 * single background-image per layer regardless of star count, and density
 * becomes a number to tune rather than a wall to hit.
 *
 * THE TWO THINGS THAT BREAK IT
 *   1. Only the part of a star inside a glyph stroke is ever visible, and
 *      strokes are a small fraction of the heading box. Density has to be set
 *      against the STROKE area, not the box — which is why these counts look
 *      absurd on paper.
 *   2. `background-clip: text` cannot clip a parent's background to glyphs that
 *      live inside a transformed descendant. GSAP SplitText produces exactly
 *      those, so a heading using this must not also use data-split.
 *
 * Deterministic PRNG: the field is identical on every build, so the generated
 * CSS does not churn in version control.
 */

/* `count` is the density knob. Halving every count halves the field; the layer
   geometry, sizes and drift are unaffected, so the look stays the same and only
   the crowding changes. Previous set was 340/190/70 (~10,300 stars across a
   750x240 heading) which read as too busy; these are half that. */
const LAYERS = [
  // tile, star count, radius range, drift (one full tile per cycle)
  { w: 96, h: 96, count: 170, rMin: 0.55, rMax: 1.05, dx: 96, dy: 96, alpha: [0.55, 0.95] },
  { w: 160, h: 160, count: 95, rMin: 0.9, rMax: 1.5, dx: 160, dy: -160, alpha: [0.7, 1.0] },
  { w: 256, h: 256, count: 35, rMin: 1.4, rMax: 2.3, dx: -256, dy: 256, alpha: [0.85, 1.0] },
]

/* Mostly white with rare colour, mirroring the hero field so the type and the
   background read as the same sky. */
const TINTS = [
  { c: '#ffffff', w: 0.9 },
  { c: '#eaf0ff', w: 0.04 },
  { c: '#36faf0', w: 0.024 },
  { c: '#ffd23c', w: 0.02 },
  { c: '#ff5a46', w: 0.012 },
]

function makeRng(seed) {
  let s = seed >>> 0
  return () => {
    s = (s * 1664525 + 1013904223) >>> 0
    return s / 4294967296
  }
}

function pickTint(r) {
  let acc = 0
  for (const t of TINTS) {
    acc += t.w
    if (r <= acc) return t.c
  }
  return '#ffffff'
}

function layerSvg(layer, rng) {
  const circles = []
  for (let i = 0; i < layer.count; i++) {
    const cx = (rng() * layer.w).toFixed(1)
    const cy = (rng() * layer.h).toFixed(1)
    const r = (layer.rMin + rng() * (layer.rMax - layer.rMin)).toFixed(2)
    const a = (layer.alpha[0] + rng() * (layer.alpha[1] - layer.alpha[0])).toFixed(2)
    circles.push(`<circle cx="${cx}" cy="${cy}" r="${r}" fill="${pickTint(rng())}" opacity="${a}"/>`)
  }
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${layer.w}" height="${layer.h}" viewBox="0 0 ${layer.w} ${layer.h}">${circles.join('')}</svg>`
  // Only the characters that would terminate the url() or the attribute need
  // escaping; leaving the rest readable keeps the generated file inspectable.
  return svg.replace(/#/g, '%23').replace(/"/g, "'").replace(/</g, '%3C').replace(/>/g, '%3E')
}

export function starfieldCss() {
  const rng = makeRng(19840917)
  const images = LAYERS.map((l) => `      url("data:image/svg+xml,${layerSvg(l, rng)}")`)
  const sizes = LAYERS.map((l) => `${l.w}px ${l.h}px`)
  const ends = LAYERS.map((l) => `${l.dx}px ${l.dy}px`)
  const total = LAYERS.reduce((n, l) => n + l.count, 0)

  return `/* ==========================================================================
   starfield.css — GENERATED by src/templates/starfield.mjs. Do not edit.
   Run \`npm run build\` to regenerate.

   ${LAYERS.length} tiled layers, ${total} stars per tile set
   (${LAYERS.map((l) => `${l.count}@${l.w}x${l.h}`).join(', ')}).
   A 750x240 heading therefore carries several thousand stars instead of the
   ~18 the hand-written gradient version could afford.

   .type-starfield must NOT be combined with data-split — SplitText wraps the
   text in transformed divs and background-clip:text cannot reach inside them.
   ========================================================================== */

.type-starfield {
  /* Fallback: solid ink wherever background-clip:text is unsupported. */
  color: var(--ink);
}

@supports ((-webkit-background-clip: text) or (background-clip: text)) {
  .type-starfield,
  .type-starfield .split-line {
    color: transparent;
    -webkit-text-fill-color: transparent;
    background-color: #06060d;
    background-image:
${images.join(',\n')};
    background-size: ${sizes.join(', ')};
    background-repeat: repeat;
    -webkit-background-clip: text;
    background-clip: text;
    animation: type-starfield-drift 26s linear infinite;
  }
}

/* On a DARK ground the near-black fill sits only a few levels below the surface
   behind it, so the letterforms all but disappear. A hairline stroke redraws the
   edges and the type reads as outlined glyphs holding a star field — which is
   the effect anyway. On a light ground the fill alone already separates, so this
   is scoped to the dark theme. */
.theme-dark .type-starfield,
.theme-dark .type-starfield .split-line {
  -webkit-text-stroke: 1px rgba(255, 255, 255, 0.66);
}

/* Each layer travels exactly one tile, in its own direction: the loop is
   seamless and the planes separate into parallax. */
@keyframes type-starfield-drift {
  to { background-position: ${ends.join(', ')}; }
}

@media (prefers-reduced-motion: reduce) {
  .type-starfield,
  .type-starfield .split-line { animation: none; }
}
`
}
